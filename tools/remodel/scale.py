"""
実寸の高さ → ブロック数の換算。

Minecraft では実寸どおり（1ブロック=1m）に高さを作ると低く見える。
ガスト 堺北花田（v6、ユーザー評価「かなりクオリティが高い」）の完成形から倍率を決めた:
  柱（地面〜軒）  実寸 3.7m → 5マス     (×1.35)
  屋根の頂部      実寸 5.5m → 7.5マス   (×1.36)
平面（幅・奥行き）は OSM のポリゴンどおり 1ブロック=1m のまま。高さだけに掛ける。
"""

HEIGHT_SCALE = 1.35


def blocks(real_m: float, minimum: int = 1) -> int:
    """実寸の高さ[m] → ブロック数（四捨五入、最低 minimum）。"""
    return max(minimum, round(real_m * HEIGHT_SCALE))


if __name__ == "__main__":
    for name, m in [("ひさし下端", 2.7), ("柱（軒）", 3.7), ("屋根の頂部", 5.5), ("2階建ての軒", 6.5), ("3階建ての軒", 9.5)]:
        print(f"{name:10s} {m:4.1f}m -> {blocks(m)} マス")
